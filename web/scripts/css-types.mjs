// css-types.mjs — write a .d.css.ts next to every CSS module, listing the classes it really has
import { readFileSync, writeFileSync, globSync } from 'node:fs'
import { basename } from 'node:path'

for (const file of globSync('src/**/*.module.css')) {
  const css = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')      // drop comments
  const names = [...new Set(css.match(/\.[A-Za-z_][\w-]*/g) ?? [])].map(n => n.slice(1)).sort()
  const lines = names.map(n => `  readonly ${JSON.stringify(n)}: string`).join('\n')
  writeFileSync(file.replace(/\.css$/, '.d.css.ts'),
    `// generated by scripts/css-types.mjs from ${basename(file)} — do not edit\n` +
    `declare const classes: {\n${lines}\n}\nexport default classes\n`)
}
